//! Generates the Unicode *simple* case folding table (decision D5, backlog E1-S4.2).
//!
//! Input: `data/CaseFolding.txt` (Unicode Character Database). Only the statuses `C`
//! (common) and `S` (simple) are used: together they form simple case folding, a
//! one-code-point-to-one-code-point mapping, so folding never changes the text length in
//! code points. `F` (full, multi-character) and `T` (Turkic) rows are skipped on purpose:
//! `İ` and `ß` stay as they are.
//!
//! Output: `$OUT_DIR/fold_table.rs` with a sorted `static FOLD: &[(u32, u32)]`.

use std::fmt::Write as _;
use std::{env, fs, path::Path};

fn main() {
    println!("cargo:rerun-if-changed=data/CaseFolding.txt");
    println!("cargo:rerun-if-changed=build.rs");
    let text = fs::read_to_string("data/CaseFolding.txt").expect("data/CaseFolding.txt");

    let mut pairs: Vec<(u32, u32)> = Vec::new();
    let mut unicode_version = String::from("unknown");
    for line in text.lines() {
        if let Some(rest) = line.strip_prefix("# CaseFolding-") {
            unicode_version = rest.trim_end_matches(".txt").to_string();
        }
        let line = line.split('#').next().unwrap_or("").trim();
        if line.is_empty() {
            continue;
        }
        let fields: Vec<&str> = line.split(';').map(str::trim).collect();
        if fields.len() < 3 || !(fields[1] == "C" || fields[1] == "S") {
            continue;
        }
        let from = u32::from_str_radix(fields[0], 16).expect("code point");
        let to = u32::from_str_radix(fields[2], 16).expect("mapping");
        pairs.push((from, to));
    }
    pairs.sort_unstable();
    pairs.dedup();
    for w in pairs.windows(2) {
        assert!(
            w[0].0 != w[1].0,
            "duplicate C/S mapping for U+{:04X}",
            w[0].0
        );
    }

    let mut out = String::new();
    writeln!(
        out,
        "// @generated by build.rs from data/CaseFolding.txt (Unicode {unicode_version})."
    )
    .unwrap();
    writeln!(
        out,
        "pub const UNICODE_VERSION: &str = {unicode_version:?};"
    )
    .unwrap();
    writeln!(
        out,
        "/// (code point, folded code point), sorted by code point; statuses C and S."
    )
    .unwrap();
    writeln!(out, "pub static FOLD: &[(u32, u32)] = &[").unwrap();
    for (from, to) in &pairs {
        writeln!(out, "    (0x{from:04X}, 0x{to:04X}),").unwrap();
    }
    writeln!(out, "];").unwrap();

    let dest = Path::new(&env::var("OUT_DIR").expect("OUT_DIR")).join("fold_table.rs");
    fs::write(dest, out).expect("write fold_table.rs");
}
